<?php
require_once __DIR__ . '/includes/config.php';
$adminUser = lms_require_admin();

$error = '';
$msg   = '';

if (isset($_POST['change'])) {
    lms_csrf_verify();
    $current = $_POST['password'] ?? '';
    $new     = $_POST['newpassword'] ?? '';
    $confirm = $_POST['confirmpassword'] ?? '';

    $query = $dbh->prepare("SELECT Password FROM admin WHERE UserName = :username");
    $query->execute([':username' => $adminUser]);
    $row = $query->fetch();

    if (!$row || !lms_verify_password($current, $row->Password)) {
        $error = 'Your current password is wrong.';
    } elseif (strlen($new) < 8) {
        $error = 'The new password must be at least 8 characters long.';
    } elseif ($new !== $confirm) {
        $error = 'New password and confirmation do not match.';
    } else {
        $update = $dbh->prepare("UPDATE admin SET Password = :pwd WHERE UserName = :username");
        $update->execute([':pwd' => lms_hash_password($new), ':username' => $adminUser]);
        $msg = 'Your password has been changed.';
    }
}
